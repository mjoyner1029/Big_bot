"""Experiment observation tracker — attributed paper/canary evidence.

An experiment may only be judged on trades generated by ITS exact
configuration. Observations are tagged with experiment_id, strategy_version,
parameter_version and signal_id so baseline trades, other experiments and
normal bot trades can never contaminate the evaluation.
"""
from __future__ import annotations

import json
import logging
import sqlite3
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

_utcnow = lambda: datetime.now(timezone.utc).isoformat()

_CREATE = """
CREATE TABLE IF NOT EXISTS experiment_observations (
    id                INTEGER PRIMARY KEY AUTOINCREMENT,
    experiment_id     TEXT NOT NULL,
    phase             TEXT NOT NULL,          -- 'paper' | 'canary'
    signal_id         TEXT,
    strategy          TEXT,
    strategy_version  TEXT,
    parameter_version TEXT,
    symbol            TEXT,
    direction         TEXT,
    net_pnl           REAL,
    gross_pnl         REAL,
    slippage_pct      REAL,
    fill_quality      REAL,
    rejected          INTEGER DEFAULT 0,      -- signal rejected (no fill)
    execution_failed  INTEGER DEFAULT 0,
    opened_at         TEXT,
    closed_at         TEXT,
    recorded_at       TEXT NOT NULL,
    metadata          TEXT
)
"""

_INDEXES = [
    "CREATE INDEX IF NOT EXISTS idx_eo_exp   ON experiment_observations(experiment_id)",
    "CREATE INDEX IF NOT EXISTS idx_eo_phase ON experiment_observations(experiment_id, phase)",
]


class ExperimentObservationTracker:
    """Records and aggregates per-experiment paper/canary observations."""

    def __init__(self, db_path: str = "data/trade_memory.sqlite") -> None:
        self.db_path = db_path
        with sqlite3.connect(self.db_path) as conn:
            conn.execute(_CREATE)
            for idx in _INDEXES:
                conn.execute(idx)
            conn.commit()

    def record_trade(
        self,
        experiment_id: str,
        phase: str,
        symbol: str,
        net_pnl: float,
        *,
        signal_id: Optional[str] = None,
        strategy: Optional[str] = None,
        strategy_version: Optional[str] = None,
        parameter_version: Optional[str] = None,
        direction: Optional[str] = None,
        gross_pnl: Optional[float] = None,
        slippage_pct: Optional[float] = None,
        fill_quality: Optional[float] = None,
        opened_at: Optional[str] = None,
        closed_at: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None,
        recorded_at: Optional[str] = None,
    ) -> int:
        with sqlite3.connect(self.db_path) as conn:
            cur = conn.execute(
                "INSERT INTO experiment_observations "
                "(experiment_id, phase, signal_id, strategy, strategy_version, "
                " parameter_version, symbol, direction, net_pnl, gross_pnl, "
                " slippage_pct, fill_quality, opened_at, closed_at, recorded_at, metadata) "
                "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                (experiment_id, phase, signal_id, strategy, strategy_version,
                 parameter_version, symbol, direction, net_pnl, gross_pnl,
                 slippage_pct, fill_quality, opened_at, closed_at or _utcnow(),
                 recorded_at or _utcnow(), json.dumps(metadata or {}, default=str)),
            )
            conn.commit()
            return int(cur.lastrowid)

    def record_rejection(self, experiment_id: str, phase: str, symbol: str,
                         reason: str, execution_failed: bool = False) -> None:
        with sqlite3.connect(self.db_path) as conn:
            conn.execute(
                "INSERT INTO experiment_observations "
                "(experiment_id, phase, symbol, rejected, execution_failed, recorded_at, metadata) "
                "VALUES (?,?,?,1,?,?,?)",
                (experiment_id, phase, symbol, int(execution_failed), _utcnow(),
                 json.dumps({"reason": reason})),
            )
            conn.commit()

    def summary(self, experiment_id: str, phase: str) -> Dict[str, Any]:
        """Aggregate ONLY this experiment's observations for the given phase."""
        with sqlite3.connect(self.db_path) as conn:
            conn.row_factory = sqlite3.Row
            rows = conn.execute(
                "SELECT * FROM experiment_observations "
                "WHERE experiment_id=? AND phase=? ORDER BY recorded_at ASC",
                (experiment_id, phase),
            ).fetchall()

        trades = [dict(r) for r in rows if not r["rejected"] and r["net_pnl"] is not None]
        rejected = sum(1 for r in rows if r["rejected"])
        failed = sum(1 for r in rows if r["execution_failed"])
        pnls = [t["net_pnl"] for t in trades]

        days = 0.0
        if rows:
            try:
                first = datetime.fromisoformat(rows[0]["recorded_at"])
                last = datetime.fromisoformat(rows[-1]["recorded_at"])
                days = (last - first).total_seconds() / 86400.0
            except (ValueError, TypeError):
                days = 0.0

        from core.validation_stats import (
            max_drawdown, profit_factor, sharpe_ratio, uncertainty_summary,
        )
        n = len(pnls)
        wins = sum(1 for p in pnls if p > 0)
        slips = [t["slippage_pct"] for t in trades if t["slippage_pct"] is not None]
        return {
            "trades": n,
            "days": days,
            "net_return": sum(pnls),
            "expectancy": (sum(pnls) / n) if n else 0.0,
            "win_rate": (wins / n) if n else 0.0,
            "profit_factor": min(profit_factor(pnls), 1e9),
            "max_drawdown": max_drawdown(pnls),
            "sharpe": sharpe_ratio(pnls),
            "avg_slippage_pct": (sum(slips) / len(slips)) if slips else None,
            "signal_frequency_per_day": (n / days) if days > 0 else 0.0,
            "rejected_signals": rejected,
            "execution_failures": failed,
            "uncertainty": uncertainty_summary(pnls),
        }

    def observations(self, experiment_id: str, phase: Optional[str] = None) -> List[Dict]:
        q = "SELECT * FROM experiment_observations WHERE experiment_id=?"
        args: list = [experiment_id]
        if phase:
            q += " AND phase=?"
            args.append(phase)
        with sqlite3.connect(self.db_path) as conn:
            conn.row_factory = sqlite3.Row
            rows = conn.execute(q, args).fetchall()
        return [dict(r) for r in rows]
